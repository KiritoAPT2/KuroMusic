private val BrokenIconSize = 24.dp

@Composable
fun BrokenIcon(
    codePoint: Int,
    filled: Boolean = false,
    contentDescription: String? = null,
    modifier: Modifier = Modifier,
    tint: Color = androidx.compose.material3.LocalContentColor.current,
    size: Dp = BrokenIconSize,
) {
    val fontFamily = remember { if (filled) BrokenIcons.fontFamilyFilled else BrokenIcons.fontFamily }
    val text = remember(codePoint) { String(Character.toChars(codePoint)) }
    Box(
        modifier = modifier.size(size),
        contentAlignment = Alignment.Center
    ) {
        Text(
            text = text,
            fontFamily = fontFamily,
            fontSize = size.value.sp,
            color = tint,
            textAlign = TextAlign.Center,
        )
    }
}
